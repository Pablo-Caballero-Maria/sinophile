/**
 * Downloads CC-CEDICT (Chinese-English dictionary, CC BY-SA 4.0, https://cc-cedict.org)
 * and writes a compact version to data/cedict.json:
 *   { source, license, generated, fields: ["hanzi","pinyin","en"], entries: [[...], ...] }
 *
 * To keep the download small (it is lazy-loaded by the dictionary page) only
 * simplified headwords of up to 4 characters are kept (proper nouns up to 3),
 * each with at most 3 definitions; pinyin is converted to tone marks and
 * entries that are mere variant/surname references are dropped.
 *
 * Run manually when you want to refresh the dictionary:  npm run dictionary
 */
import { gunzipSync } from "node:zlib";
import { writeFileSync } from "node:fs";
import { numberedToMarked } from "../src/lib/pinyin.ts";

const SOURCE_URL = "https://www.mdbg.net/chinese/export/cedict/cedict_1_0_ts_utf-8_mdbg.txt.gz";
const OUT = new URL("../data/cedict.json", import.meta.url);

const LINE_RE = /^(\S+) (\S+) \[([^\]]*)\] \/(.*)\/\s*$/;
const MAX_CHARS = 4;
const MAX_PROPER_CHARS = 3;
const MAX_DEFS = 3;
const NOISE_RE = /^(old |archaic |ancient |Japanese |Korean )?variant of |^surname |^see [^/]+$|^\(old\) variant/i;

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`Download failed: ${response.status}`);
const text = gunzipSync(Buffer.from(await response.arrayBuffer())).toString("utf8");

const merged = new Map<string, [string, string, string[]]>();
for (const line of text.split("\n")) {
  if (line.startsWith("#")) continue;
  const m = line.match(LINE_RE);
  if (!m) continue;
  const [, , simplified, rawPinyin, rawDefs] = m;
  const defs = rawDefs.split("/").filter((d) => d && !NOISE_RE.test(d));
  if (defs.length === 0) continue;
  const pinyin = numberedToMarked(rawPinyin, true);
  const length = [...simplified].length;
  const isProperNoun = /^[A-ZĀÁǍÀĒÉĚÈŌÓǑÒ]/.test(pinyin);
  if (length > MAX_CHARS || (isProperNoun && length > MAX_PROPER_CHARS)) continue;
  const key = `${simplified}|${pinyin.toLowerCase()}`;
  const existing = merged.get(key);
  if (existing) existing[2].push(...defs.filter((d) => !existing[2].includes(d)));
  else merged.set(key, [simplified, pinyin, defs]);
}

const entries = [...merged.values()].map(([h, p, d]) => [h, p, d.slice(0, MAX_DEFS).join("; ")]);
const meta = {
  source: "CC-CEDICT (https://cc-cedict.org) — generated by scripts/build-dictionary.ts",
  license: "CC BY-SA 4.0",
  generated: new Date().toISOString().slice(0, 10),
  fields: ["hanzi", "pinyin", "en"],
};
// One entry per line keeps diffs readable and the file greppable.
const body = entries.map((e) => JSON.stringify(e)).join(",\n");
const json = JSON.stringify(meta, null, 2).replace(/\n}$/, `,\n  "entries": [\n${body}\n]\n}\n`);
writeFileSync(OUT, json);
console.log(`cedict.json: ${entries.length} entries, ${(json.length / 1e6).toFixed(1)} MB`);
